    /// <summary>
    /// 尝试获取指定英雄某一定位（按 <see cref="HeroDisplayHelper.StandardRoles"/> 顺序）的等级。
    /// </summary>
    public static bool TryGetLevel(int heroId, int roleIndex, out int level)
    {
        if (Levels.TryGetValue(heroId, out var levels)
            && roleIndex >= 0
            && roleIndex < levels.Length)
        {
            level = levels[roleIndex];
            return true;
        }

        level = 0;
        return false;
    }
